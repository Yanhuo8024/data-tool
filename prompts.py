def _load_overrides() -> Dict[str, str]:
    """加载 data/prompt_versions.json 中的版本覆盖"""
    try:
        if _OVERRIDE_FILE.exists():
            data = json.loads(_OVERRIDE_FILE.read_text(encoding='utf-8'))
            if isinstance(data, dict) and 'prompts' in data and isinstance(data['prompts'], dict):
                return data['prompts']
    except (json.JSONDecodeError, OSError):
        pass
    return {}


_overrides_cache: Optional[Dict[str, str]] = None
_overrides_mtime: float = 0.0


def _overrides() -> Dict[str, str]:
    """带 mtime 缓存的覆盖表（文件变化时自动重读）"""
    global _overrides_cache, _overrides_mtime
    try:
        mtime = _OVERRIDE_FILE.stat().st_mtime if _OVERRIDE_FILE.exists() else 0.0
    except OSError:
        mtime = 0.0
    if _overrides_cache is None or mtime != _overrides_mtime:
        _overrides_cache = _load_overrides()
        _overrides_mtime = mtime
    return _overrides_cache


def get_prompt(name: str) -> str:
    """获取提示词：覆盖版本优先，其次代码默认基线"""
    return _overrides().get(name) or DEFAULT_PROMPTS.get(name, "")


def set_prompt(name: str, text: str) -> Dict:
    """持久化覆盖提示词到 data/prompt_versions.json（版本化热更新）"""
    global _overrides_cache, _overrides_mtime
    _DATA_DIR.mkdir(parents=True, exist_ok=True)
    overrides = _load_overrides()
    overrides[name] = text
    payload = {
        'updated_at': time.strftime('%Y-%m-%d %H:%M:%S'),
        'prompts': overrides,
    }
    _OVERRIDE_FILE.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf-8')
    _overrides_cache = dict(overrides)
    _overrides_mtime = _OVERRIDE_FILE.stat().st_mtime
    return payload


def get_all_versions() -> Dict:
    """返回全部提示词当前生效版本（供管理界面展示）"""
    result = {}
    for name in DEFAULT_PROMPTS:
        result[name] = get_prompt(name)
    return result


def resolve_domain_prompt(message: str) -> str:
    """按问题领域返回人设提示词：税务 > 金融 > 通用"""
    base = get_prompt('domain_base') + get_prompt('human_style')
    for key, words in DOMAIN_KEYWORDS.items():
        if any(w in message for w in words):
            if key == 'domain_tax':
                return (get_prompt('domain_tax') + base +
                        "涉及税率与政策时，注明『以最新政策为准，具体以主管税务机关口径为准』。")
            if key == 'domain_finance':
                return (get_prompt('domain_finance') + base +
                        "涉及具体利率、费率、产品条款时，注明『以银行/机构最新公布为准』。")
    return "你是用户的智能信息检索助手，讲人话。" + base
